export function interpolate(template, values = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ""));
}

export function createTranslator(locale) {
  const dictionary = i18nConfig.translations[locale] ?? i18nConfig.translations[i18nConfig.defaultLocale];
  const fallback = i18nConfig.translations[i18nConfig.defaultLocale];

  return function translate(key, values) {
    return interpolate(dictionary[key] ?? fallback[key] ?? key, values);
  };
}
